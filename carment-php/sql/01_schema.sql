CREATE EXTENSION IF NOT EXISTS btree_gist; -- dipakai biar reservasi aktif tidak tumpang-tindih

DROP TABLE IF EXISTS feedback, kode_pemulihan, reset_password, keranjang, inspeksi, maintenance,
                     reservasi, barang, kategori, jam_toko, users CASCADE;

-- ---------- Akun & pengaturan toko ----------
CREATE TABLE users (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama     VARCHAR(100) NOT NULL,
    email    VARCHAR(100) NOT NULL UNIQUE,
    hp       VARCHAR(20),
    password VARCHAR(255) NOT NULL,                               -- hash (password_hash)
    role     VARCHAR(10)  NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'staff', 'owner'))
);

CREATE TABLE jam_toko (                                           -- jadwal buka, diedit staff
    hari  SMALLINT PRIMARY KEY CHECK (hari BETWEEN 1 AND 7),      -- 1 = Senin ... 7 = Minggu
    buka  TIME,
    tutup TIME,                                                   -- buka & tutup NULL = libur
    CHECK ((buka IS NULL AND tutup IS NULL) OR (buka IS NOT NULL AND tutup IS NOT NULL AND buka < tutup))
);

-- ---------- Katalog ----------
CREATE TABLE kategori (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE barang (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(120) NOT NULL,
    kategori    VARCHAR(30)  NOT NULL,
    harga       INT NOT NULL,                                     -- sewa per hari
    deposit     INT NOT NULL DEFAULT 0,
    spesifikasi TEXT,
    kondisi     TEXT,
    status      VARCHAR(12) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available', 'Rented', 'Maintenance')),
    foto_url    VARCHAR(255),                                     -- gambar/asli/<nama file>
    foto_nama   VARCHAR(120),                                     -- thumbnail: gambar/thumb/<nama file>
    CONSTRAINT barang_kategori_fk FOREIGN KEY (kategori) REFERENCES kategori(nama) ON UPDATE CASCADE
);

-- ---------- Transaksi ----------
CREATE TABLE reservasi (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INT NOT NULL REFERENCES users(id),
    barang_id        INT NOT NULL REFERENCES barang(id),
    tgl_mulai        DATE NOT NULL,
    tgl_selesai      DATE NOT NULL,
    sewa             INT NOT NULL,
    deposit          INT NOT NULL,
    denda            INT NOT NULL DEFAULT 0,
    status           VARCHAR(20) NOT NULL DEFAULT 'Menunggu',
    batas_bayar      TIMESTAMP,                                   -- batas pelunasan / perbaikan pembayaran
    bukti            VARCHAR(100),                                -- bukti pembayaran
    bukti_lama       VARCHAR(100),                                -- bukti sebelum diperbaiki pelanggan
    catatan_customer TEXT,
    alasan_tolak     TEXT,                                        -- alasan staff menolak pembayaran
    refund_bank      VARCHAR(40),
    refund_rekening  VARCHAR(40),
    refund_nama      VARCHAR(80),
    bukti_refund     VARCHAR(100),                                -- bukti pengembalian dana dari staff
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reservasi_status_check CHECK (status IN (
        'Menunggu Pembayaran', 'Menunggu', 'Perlu Perbaikan', 'Dikonfirmasi',
        'Dipinjam', 'Selesai', 'Ditolak', 'Dibatalkan', 'Menunggu Refund', 'Dikembalikan'
    )),
    CONSTRAINT reservasi_tanpa_bentrok EXCLUDE USING gist (       -- tanggal yang masih terkunci/terpakai tidak boleh bertabrakan
        barang_id WITH =, daterange(tgl_mulai, tgl_selesai, '[]') WITH &&
    ) WHERE (status IN ('Menunggu Pembayaran', 'Menunggu', 'Perlu Perbaikan', 'Dikonfirmasi', 'Dipinjam'))
);

CREATE INDEX idx_res_barang_tgl ON reservasi (barang_id, tgl_mulai, tgl_selesai);

CREATE TABLE keranjang (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    barang_id   INT NOT NULL REFERENCES barang(id) ON DELETE CASCADE,
    tgl_mulai   DATE NOT NULL,
    tgl_selesai DATE NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Pengembalian unit & perawatan ----------
CREATE TABLE inspeksi (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservasi_id INT NOT NULL REFERENCES reservasi(id),
    kondisi      VARCHAR(12) NOT NULL CHECK (kondisi IN ('Baik', 'Kurang Baik', 'Rusak')),
    catatan      TEXT,
    tgl          DATE NOT NULL
);

CREATE TABLE maintenance (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barang_id INT NOT NULL REFERENCES barang(id),
    masalah   TEXT NOT NULL,
    status    VARCHAR(7) NOT NULL DEFAULT 'Dibuka' CHECK (status IN ('Dibuka', 'Selesai')),
    tgl       DATE NOT NULL
);

-- ---------- Pemulihan akun & feedback ----------
CREATE TABLE reset_password (                                     -- token atur-ulang sandi (hash), sekali pakai
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    dipakai    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE kode_pemulihan (                                     -- kode verifikasi 6 digit yang dikirim lewat email
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kode_hash  VARCHAR(255) NOT NULL,                             -- disimpan ter-hash, bukan teks asli
    expires_at TIMESTAMP NOT NULL,
    percobaan  SMALLINT NOT NULL DEFAULT 0,
    dipakai    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_kode_user ON kode_pemulihan (user_id);

CREATE TABLE feedback (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT REFERENCES users(id) ON DELETE SET NULL,        -- NULL = pengunjung tanpa akun
    nama       VARCHAR(60) NOT NULL,
    rating     SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    pesan      TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);