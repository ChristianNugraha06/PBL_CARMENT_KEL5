CREATE TABLE IF NOT EXISTS kode_pemulihan (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kode_hash  VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    percobaan  SMALLINT NOT NULL DEFAULT 0,
    dipakai    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kode_user ON kode_pemulihan (user_id);

CREATE TABLE IF NOT EXISTS feedback (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT REFERENCES users(id) ON DELETE SET NULL,
    nama       VARCHAR(60) NOT NULL,
    rating     SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    pesan      TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);