CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------- Kategori & barang ----------
CREATE TABLE IF NOT EXISTS kategori (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(30) NOT NULL UNIQUE
);

INSERT INTO kategori (nama) VALUES ('Kamera'), ('Lensa'), ('Aksesori')
ON CONFLICT (nama) DO NOTHING;

INSERT INTO kategori (nama)
SELECT DISTINCT kategori FROM barang
ON CONFLICT (nama) DO NOTHING;

ALTER TABLE barang DROP CONSTRAINT IF EXISTS barang_kategori_check;
ALTER TABLE barang DROP CONSTRAINT IF EXISTS barang_kategori_fk;
ALTER TABLE barang ALTER COLUMN kategori TYPE VARCHAR(30);
ALTER TABLE barang ADD CONSTRAINT barang_kategori_fk FOREIGN KEY (kategori) REFERENCES kategori(nama) ON UPDATE CASCADE;
ALTER TABLE barang ADD COLUMN IF NOT EXISTS foto_url  VARCHAR(255);
ALTER TABLE barang ADD COLUMN IF NOT EXISTS foto_nama VARCHAR(120);

-- ---------- Reservasi ----------
ALTER TABLE reservasi DROP CONSTRAINT IF EXISTS reservasi_status_check;
ALTER TABLE reservasi DROP CONSTRAINT IF EXISTS reservasi_tanpa_bentrok;
ALTER TABLE reservasi ALTER COLUMN status TYPE VARCHAR(20);
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS batas_bayar      TIMESTAMP;
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS bukti_lama       VARCHAR(100);
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS catatan_customer TEXT;
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS alasan_tolak     TEXT;
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS refund_bank      VARCHAR(40);
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS refund_rekening  VARCHAR(40);
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS refund_nama      VARCHAR(80);
ALTER TABLE reservasi ADD COLUMN IF NOT EXISTS bukti_refund     VARCHAR(100);

ALTER TABLE reservasi ADD CONSTRAINT reservasi_status_check CHECK (status IN (
    'Menunggu Pembayaran', 'Menunggu', 'Perlu Perbaikan', 'Dikonfirmasi',
    'Dipinjam', 'Selesai', 'Ditolak', 'Dibatalkan', 'Menunggu Refund', 'Dikembalikan'
));

ALTER TABLE reservasi ADD CONSTRAINT reservasi_tanpa_bentrok EXCLUDE USING gist (
    barang_id WITH =, daterange(tgl_mulai, tgl_selesai, '[]') WITH &&
) WHERE (status IN ('Menunggu Pembayaran', 'Menunggu', 'Perlu Perbaikan', 'Dikonfirmasi', 'Dipinjam'));

-- ---------- Inspeksi (kondisi "Kurang Baik") ----------
ALTER TABLE inspeksi DROP CONSTRAINT IF EXISTS inspeksi_kondisi_check;
ALTER TABLE inspeksi ALTER COLUMN kondisi TYPE VARCHAR(12);
ALTER TABLE inspeksi ADD CONSTRAINT inspeksi_kondisi_check CHECK (kondisi IN ('Baik', 'Kurang Baik', 'Rusak'));

-- ---------- Tabel baru ----------
CREATE TABLE IF NOT EXISTS keranjang (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    barang_id   INT NOT NULL REFERENCES barang(id) ON DELETE CASCADE,
    tgl_mulai   DATE NOT NULL,
    tgl_selesai DATE NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reset_password (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    dipakai    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS jam_toko (
    hari  SMALLINT PRIMARY KEY CHECK (hari BETWEEN 1 AND 7),
    buka  TIME,
    tutup TIME,
    CHECK ((buka IS NULL AND tutup IS NULL) OR (buka IS NOT NULL AND tutup IS NOT NULL AND buka < tutup))
);

